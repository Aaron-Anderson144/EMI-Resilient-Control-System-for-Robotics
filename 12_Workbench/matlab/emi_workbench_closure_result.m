function study = emi_workbench_closure_result(outputFolder)
% Read short/long-return diagnostics; never include them in primary scoring.
arguments
    outputFolder (1,1) string
end
summary = jsondecode(fileread(fullfile(outputFolder, 'stage_summary.json')));
assert(strcmp(summary.stage, 'closure_diagnostic') && summary.excluded_from_primary_evaluation, ...
    'EMIWorkbench:ClosureStage', 'Return sensitivity must remain a diagnostic excluded from primary evaluation.');
assert(summary.expected_records == 256, 'EMIWorkbench:ClosureScope', ...
    'Return sensitivity requires 256 declared records.');
records = readtable(fullfile(outputFolder, 'record_index.csv'), 'TextType', 'string', 'VariableNamingRule', 'preserve');
assert(height(records) == summary.logical_records && ismember('Status', records.Properties.VariableNames), ...
    'EMIWorkbench:ClosureRecords', 'Saved return-sensitivity record count differs from its summary.');
study = struct('summary', summary, 'comparisons', struct([]), ...
    'failedRecords', sum(records.Status ~= "passed"), 'receiverHypotheses', 0, 'domainNumericsPass', false);
if summary.comparison_pairs > 0
    comparisons = readtable(fullfile(outputFolder, 'closure_comparisons.csv'), 'TextType', 'string', 'VariableNamingRule', 'preserve');
    columns = {'Fixture','Variant','Arm','Ccp_pF','ReturnSensitivityRMSE_deg','ReturnSensitivityPeak_deg', ...
        'ShortReturnPeakCountError','LongReturnPeakCountError','ShortReturnFinalCountError','LongReturnFinalCountError', ...
        'ShortReturnDomainNumericsPass','LongReturnDomainNumericsPass'};
    assert(height(comparisons) == summary.comparison_pairs && all(ismember(columns, comparisons.Properties.VariableNames)), ...
        'EMIWorkbench:ClosureComparisons', 'Saved return-sensitivity comparisons differ from the declared count or required fields.');
    study.comparisons = table2struct(comparisons(:, columns));
    study.receiverHypotheses = numel(unique(comparisons.Variant));
    study.domainNumericsPass = summary.complete && summary.comparison_pairs == 128 && ...
        all(comparisons.ShortReturnDomainNumericsPass & comparisons.LongReturnDomainNumericsPass);
end
if summary.complete
    assert(summary.logical_records == 256 && study.failedRecords == 0 && summary.comparison_pairs == 128 && ...
        study.receiverHypotheses == 16 && numel(unique(comparisons.Fixture)) == 2 && ...
        height(unique(comparisons(:, {'Fixture','Variant','Arm'}))) == 128, ...
        'EMIWorkbench:ClosureCoverage', 'A completed diagnostic must retain 256 records and 128 distinct return comparisons.');
end
end
