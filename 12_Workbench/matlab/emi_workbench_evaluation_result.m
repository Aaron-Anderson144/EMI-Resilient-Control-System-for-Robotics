function study = emi_workbench_evaluation_result(outputFolder)
% Read saved evaluation evidence without rerunning or pooling benefit screens.
arguments
    outputFolder (1,1) string
end
summary = jsondecode(fileread(fullfile(outputFolder, 'stage_summary.json')));
assert(strcmp(summary.partition, 'evaluation'), 'EMIWorkbench:EvaluationPartition', ...
    'The evaluation workflow requires evaluation results.');
assert(summary.receiver_hypotheses == 16 && summary.expected_records == 1536, ...
    'EMIWorkbench:EvaluationScope', 'Evaluation requires 16 receiver assumptions and 1536 declared records.');
study = struct('summary', summary, 'pairs', struct([]), 'hypotheses', struct([]));
columns = {'Fixture','Variant','Arm','ReceiverDomainPass','ReceiverNumericsPass', ...
    'CleanGuardPass','ExecutionGuardPass','WindowPairedRMSE_deg','WindowPairedPeak_deg', ...
    'PeakCurrent_A','EMICountPeak_counts','EMICountFinal_counts','TaskSuccess'};
if summary.paired_results > 0
    metrics = readtable(fullfile(outputFolder, 'metrics.csv'), 'TextType', 'string', 'VariableNamingRule', 'preserve');
    assert(all(ismember(columns, metrics.Properties.VariableNames)) && height(metrics) == summary.paired_results, ...
        'EMIWorkbench:EvaluationMetrics', 'Saved evaluation metrics do not match the declared pair count or required fields.');
    study.pairs = table2struct(metrics(:, columns));
end
if isfield(summary, 'assessment')
    study.hypotheses = summary.assessment.hypotheses;
    assert(numel(study.hypotheses) == 16, 'EMIWorkbench:EvaluationAssessment', ...
        'A complete evaluation assessment must preserve all 16 receiver hypotheses.');
    identities = arrayfun(@(item) string(item.variant.id), study.hypotheses);
    assert(numel(unique(identities)) == 16 && ...
        summary.assessment.passing_hypotheses == sum([study.hypotheses.combined_benefit_demonstrated]) && ...
        summary.assessment.all_hypotheses_pass == all([study.hypotheses.combined_benefit_demonstrated]), ...
        'EMIWorkbench:EvaluationAssessment', 'Per-hypothesis benefit outcomes disagree with the saved assessment.');
end
if summary.complete
    assert(summary.logical_records == 1536 && summary.paired_results == 768 && ...
        summary.failed_records == 0 && summary.failed_pairs == 0 && ...
        numel(unique(metrics.Variant)) == 16 && numel(unique(metrics.Fixture)) == 12 && ...
        height(unique(metrics(:, {'Fixture','Variant','Arm'}))) == 768 && numel(study.hypotheses) == 16, ...
        'EMIWorkbench:EvaluationCoverage', 'A completed evaluation must retain all 1536 records, 768 distinct comparisons, and 16 screens.');
end
end
