function result = run_experiment(outputRoot)
%RUN_EXPERIMENT Train and test physics plus learned innovation corrections.
% All data are simulated. This function never commands a motor or changes
% the original project. Existing result folders are retained on rerun.
root=fileparts(mfilename('fullpath'));
if nargin<1,outputRoot=fullfile(root,'results');end
oldPath=path; restore=onCleanup(@()path(oldPath)); %#ok<NASGU>
addpath(fullfile(root,'code'));
if ~isfolder(outputRoot),mkdir(outputRoot);end
runDir=string(tempname(outputRoot));mkdir(runDir);
referenceRoot=fullfile(root,'reference_project');
plan=struct('schema','hybrid-innovation-study-v1','createdLocal',char(datetime('now')), ...
    'sampleTime_s',.001,'duration_s',3,'warmupSeconds',.2,'originStride',20, ...
    'trainingSeeds',[110101:110108,110201:110208,110301:110308], ...
    'validationSeeds',[120101:120104,120201:120204,120301:120304], ...
    'testSeeds',[130101:130110,130201:130210,130301:130310,130401:130410], ...
    'trainingRegimes',["nominal","varied","nonlinear"], ...
    'testRegimes',["nominal","varied","nonlinear","stress"], ...
    'trainingRunsPerRegime',8,'validationRunsPerRegime',4,'testRunsPerRegime',10, ...
    'candidateDegrees',[1,2],'candidateDelays',[2,5,10], ...
    'candidateRidge',[1e-10,1e-6,1e-3],'svdTolerance',1e-9, ...
    'selectionHorizonSamples',50,'testHorizonsSamples',[1,20,50,100,250], ...
    'selection','Lowest equal-run mean validation 50 ms truth endpoint RMSE, separately for degree 1 and degree 2. Fixed warmup yields identical origins for all candidates.', ...
    'trainingTarget','Received encoder position minus nominal healthy observer prior position. Only causal measured position and applied voltage enter preprocessing or regression.', ...
    'truthUse','Simulation truth is used only for offline model selection and evaluation; never as a fitting target, regressor, observer input, or forecast input.', ...
    'primaryOutput','Predicted encoder position C*xprior+rhat, scored against physical position truth and measured position. Internal posterior position is a distinct auxiliary quantity.', ...
    'baselines',["Nominal physics","Persistent innovation","Linear hybrid"], ...
    'persistentWindowSamples',20, ...
    'benefitScreen','In each regime, EDMD must reduce mean 50 ms RMSE by at least 10 percent against each of the three baselines, win at least 7 of 10 paired runs against each, and produce no nonfinite tested forecasts.', ...
    'screenMeaning','Predefined research screen, not a control requirement or safety certificate.', ...
    'bootstrap','10000 paired trajectory resamples; percentile 95 percent intervals; descriptive and not adjusted for multiple regimes.', ...
    'modelPolicy','No test-driven retuning, no post-hoc clipping, no selection based on test outcomes.', ...
    'scope','Offline shadow prototype with synchronous healthy data and recorded future voltage sequences; no receiver, EMI exposure, packet-recovery, control intervention, hardware or closed-loop stability claim.', ...
    'contributor',struct('name','Larry Anderson','role','Research collaborator and technical adviser'));
hybrid_write_json(fullfile(runDir,'study_plan.json'),plan);
fprintf('HYBRID_OUTPUT %s\n',runDir);
[training,trainingMeta]=study_generate_records(referenceRoot,plan.trainingSeeds, ...
    repelem(plan.trainingRegimes,plan.trainingRunsPerRegime),plan.duration_s);
[validation,validationMeta]=study_generate_records(referenceRoot,plan.validationSeeds, ...
    repelem(plan.trainingRegimes,plan.validationRunsPerRegime),plan.duration_s);
residualTraining=hybrid_prepare_records(training);
save(fullfile(runDir,'development_records.mat'),'training','validation','trainingMeta','validationMeta','-v7.3');
rows=table;allModels={};candidate=0;
for degree=plan.candidateDegrees
    for delay=plan.candidateDelays
        for ridge=plan.candidateRidge
            candidate=candidate+1;started=tic;
            model=edmd_fit(residualTraining,degree=degree,delay=delay,ridge=ridge,svdTolerance=plan.svdTolerance);
            [~,scores]=hybrid_score({model},"candidate",validation, ...
                plan.selectionHorizonSamples,plan.originStride,plan.warmupSeconds);
            score=mean(scores.truthRMSE);
            entry=table(candidate,degree,delay,ridge,model.training.featureCount, ...
                model.training.regressorRank,model.spectralRadius,score,toc(started), ...
                'VariableNames',{'candidateId','degree','delay','ridge','features','rank', ...
                'spectralRadius','validation50msRMSE_rad','fitAndScoreSeconds'});
            rows=[rows;entry];allModels{candidate}=model; %#ok<AGROW>
            writetable(rows,fullfile(runDir,'validation_candidates.csv'));
            fprintf('Candidate %d/18: degree %d delay %d ridge %.1e; 50ms %.6g degrees\n', ...
                candidate,degree,delay,ridge,rad2deg(score));
        end
    end
end
selected=zeros(1,2);
for degree=1:2
    ids=find(rows.degree==degree);[best,j]=min(rows.validation50msRMSE_rad(ids));
    assert(isfinite(best),'Hybrid:NoFiniteCandidate','No finite validation candidate.');
    selected(degree)=ids(j);
end
models=[{[],[]},allModels(selected)];
names=["Nominal physics","Persistent innovation","Linear hybrid","EDMD hybrid"];
selection=rows(selected,:);writetable(selection,fullfile(runDir,'selected_models.csv'));
save(fullfile(runDir,'selected_models.mat'),'models','names','selection');
hybrid_write_json(fullfile(runDir,'selection_frozen.json'),struct( ...
    'selectedCandidateIds',selected,'selectionCompleteBeforeTestGeneration',true, ...
    'criterion',plan.selection,'timeLocal',char(datetime('now'))));
fprintf('MODEL_SELECTION_FROZEN. Generating untouched test seeds.\n');
[test,testMeta]=study_generate_records(referenceRoot,plan.testSeeds, ...
    repelem(plan.testRegimes,plan.testRunsPerRegime),plan.duration_s);
save(fullfile(runDir,'test_records.mat'),'test','testMeta','-v7.3');
[summary,perRun]=hybrid_score(models,names,test,plan.testHorizonsSamples,plan.originStride,plan.warmupSeconds);
writetable(summary,fullfile(runDir,'forecast_summary.csv'));
writetable(perRun,fullfile(runDir,'forecast_per_run.csv'));
[regimeSummary,comparisons,benefit]=hybrid_summarize(perRun,plan,runDir);
hybrid_make_figures(regimeSummary,test,models,names,runDir);
result=struct('outputDirectory',runDir,'trainingRuns',numel(training),'validationRuns',numel(validation), ...
    'testRuns',numel(test),'selectedCandidateIds',selected,'benefitScreen',benefit, ...
    'scope',plan.scope,'completedLocal',char(datetime('now')));
hybrid_write_json(fullfile(runDir,'execution.json'),result);
hybrid_write_json(fullfile(outputRoot,'latest_run.json'),struct('folder',string(localFolder(runDir))));
disp(selection);disp(comparisons);fprintf('HYBRID_COMPLETE %s\n',runDir);
end

function name=localFolder(p)
[~,name]=fileparts(p);
end
